fn route_rows(routes: [RouteSpec; 2]) -> Vec<RealSlicePrefillRouteRow> {
    routes
        .into_iter()
        .enumerate()
        .map(|(row_id, route)| RealSlicePrefillRouteRow {
            row_id: row_id as u64,
            token_id: 4 + row_id as u32,
            routes: vec![RealSliceRoute {
                expert_id: route.expert_id,
                owner: route.owner.to_owned(),
                score: route.score,
                corrected_score: route.corrected_score,
                normalized_weight: 1.0,
            }],
        })
        .collect()
}

fn rows(values: [[f32; 2]; 2]) -> Vec<Vec<f32>> {
    values.into_iter().map(Vec::from).collect()
}
